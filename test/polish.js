const http = require('http'), fs = require('fs'); const { app } = require('electron')
http.createServer((q, r) => { if (q.url === '/slow') { r.setHeader('content-type', 'text/html'); r.write('<title>Slow page</title><h1>loading'); setTimeout(() => r.end(' done</h1>'), 2500); return } r.setHeader('content-type', 'text/html'); r.end(`<title>Hello page</title><body style="background:linear-gradient(135deg,#ffd6a5,#bde0fe);height:100vh;margin:0;font:40px sans-serif;display:grid;place-items:center">Preview me</body>`) }).listen(48180)
fs.rmSync('/tmp/lumen-pol', { recursive: true, force: true }); app.setPath('userData', '/tmp/lumen-pol')
const L = require('../src/main.js'); const wait = ms => new Promise(r => setTimeout(r, ms))
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++ }
app.whenReady().then(async () => {
  await wait(4000); const w = L.windows[0], ex = s => w.ui.webContents.executeJavaScript(s)
  const errors = []; w.ui.webContents.on('console-message', e => { if (e.level === 'error' || e.level === 3) errors.push(e.message) })
  await ex(`document.querySelector('#intro .skip') && document.querySelector('#intro .skip').click()`); await wait(2500)
  await ex(`document.querySelector('#intro .go') && document.querySelector('#intro .go').click()`); await wait(1000)
  const a = w.createTab('http://127.0.0.1:48180/a', { active: true }); await wait(1500)
  const s = w.createTab('http://127.0.0.1:48180/slow', { active: true }); await wait(900)
  ok(await ex(`document.getElementById('loadbar').classList.contains('show')`), 'loading bar shows while loading')
  const p1 = await ex(`getComputedStyle(document.querySelector('#loadbar i')).transform`); await wait(500)
  fs.writeFileSync('/tmp/lumen-shots/pol-loadbar.png', (await w.ui.webContents.capturePage({ x: 0, y: 0, width: 1280, height: 110 })).toPNG())
  ok(p1 !== 'none', 'bar fills ' + p1)
  await wait(2500)
  ok(!(await ex(`document.getElementById('loadbar').classList.contains('show')`)), 'bar gone after load')
  await ex(`tcShow(${a.id}, document.querySelector('.tab[data-id="${a.id}"]'))`); await wait(1500)
  ok(await ex(`document.getElementById('tabcard').classList.contains('show') && !document.getElementById('tabcard').classList.contains('nothumb')`), 'hover preview with live thumbnail')
  ok(w.overlay === true && w.quietOverlay === true, 'preview raised quietly')
  fs.writeFileSync('/tmp/lumen-shots/pol-preview.png', (await w.ui.webContents.capturePage()).toPNG())
  await ex(`tcHide()`); await wait(600)
  ok(w.overlay === false, 'overlay released')
  // equalizer
  a.audible = true; w.pushState(); await wait(300)
  ok(await ex(`getComputedStyle(document.querySelector('.tab[data-id="${a.id}"] .eq')).display === 'flex'`), 'equalizer on playing tab')
  // fullscreen state
  w.win.isFullScreen = () => true; w.pushState(); await wait(300)
  ok(await ex(`document.body.classList.contains('winfs')`), 'fullscreen known from state')
  ok(!errors.length, 'no UI errors ' + errors.join('|'))
  console.log(fails ? 'FAILED' : 'ALL PASS'); app.exit(fails ? 1 : 0)
})
