const http = require('http'), fs = require('fs'); const { app } = require('electron')
http.createServer((q, r) => {
  if (q.url.startsWith('/translate_a')) { let b = ''; q.on('data', d => b += d); q.on('end', () => { const qs = new URLSearchParams(b).getAll('q'); setTimeout(() => { r.setHeader('content-type', 'application/json'); r.end(JSON.stringify(qs.map(t => ['EN ' + t.length]))) }, 500) }); return }
  r.setHeader('content-type', 'text/html; charset=utf-8')
  r.end(`<html lang="ar" dir="rtl"><title>صفحة</title><body><h1>مرحبا بكم</h1>${Array.from({ length: 260 }, (_, i) => `<p>هذه فقرة رقم ${i} من النص العربي</p>`).join('')}<div dir="rtl" id="box">صندوق</div></body></html>`)
}).listen(48150)
process.env.LUMEN_TR_API = 'http://127.0.0.1:48150'
fs.rmSync('/tmp/lumen-tr', { recursive: true, force: true }); app.setPath('userData', '/tmp/lumen-tr')
const L = require('../src/main.js'); const wait = ms => new Promise(r => setTimeout(r, ms))
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++ }
app.whenReady().then(async () => {
  await wait(4000); const w = L.windows[0], ex = s => w.ui.webContents.executeJavaScript(s)
  const errors = []; w.ui.webContents.on('console-message', e => { if (e.level === 'error' || e.level === 3) errors.push(e.message) })
  await ex(`document.querySelector('#intro .skip') && document.querySelector('#intro .skip').click()`); await wait(2500)
  await ex(`document.querySelector('#intro .go') && document.querySelector('#intro .go').click()`); await wait(1000)
  L.D.settings.set({ translateTo: 'en', offerTranslate: false })
  const t = w.createTab('http://127.0.0.1:48150/', { active: true }); await wait(2000)
  const pg = s => t.view.webContents.executeJavaScript(s)
  ok(await pg(`getComputedStyle(document.body).direction`) === 'rtl', 'page starts right-to-left')
  ex(`0`); const p = ex(`api.do('translate')`)
  await wait(700)
  ok(await ex(`document.getElementById('trcard').classList.contains('show')`), 'card shows')
  fs.writeFileSync('/tmp/lumen-shots/tr-1.png', (await w.ui.webContents.capturePage()).toPNG())
  await wait(500)
  const w1 = await ex(`parseFloat(document.getElementById('tr-fill').style.width)`)
  fs.writeFileSync('/tmp/lumen-shots/tr-2.png', (await w.ui.webContents.capturePage()).toPNG())
  ok(w1 > 5 && w1 < 100, 'bar moving ' + w1 + ' / ' + await ex(`document.getElementById('tr-count').textContent`))
  await wait(2500)
  ok(await ex(`document.getElementById('trcard').classList.contains('done') || !document.getElementById('trcard').classList.contains('show')`), 'done state')
  ok(await pg(`getComputedStyle(document.body).direction`) === 'ltr', 'flipped to left-to-right')
  ok(await pg(`document.documentElement.lang`) === 'en', 'lang set to en')
  ok(await pg(`document.getElementById('box').getAttribute('dir')`) === 'ltr', 'inner dir flipped')
  ok(/^EN/.test(await pg(`document.querySelector('h1').textContent`)), 'text translated')
  await wait(1500)
  ok(!(await ex(`document.getElementById('trcard').classList.contains('show')`)), 'card closed')
  // show original
  await ex(`api.do('translate')`); await wait(800)
  ok(await pg(`getComputedStyle(document.body).direction`) === 'rtl' && await pg(`document.documentElement.lang`) === 'ar' && await pg(`document.getElementById('box').getAttribute('dir')`) === 'rtl', 'original restored rtl')
  // cancel
  ex(`api.do('translate')`); await wait(900)
  await ex(`document.getElementById('tr-cancel').click()`); await wait(2500)
  ok(await pg(`!document.documentElement.dataset.lumenTranslated && getComputedStyle(document.body).direction === 'rtl'`), 'cancel leaves page original')
  ok(!(await ex(`document.getElementById('trcard').classList.contains('show')`)), 'card gone after cancel')
  ok(!errors.length, 'no UI errors ' + errors.join('|'))
  console.log(fails ? 'FAILED' : 'ALL PASS'); app.exit(fails ? 1 : 0)
})
