const fs = require('fs'); const { app, Menu } = require('electron')
fs.rmSync('/tmp/lumen-20', { recursive: true, force: true }); app.setPath('userData', '/tmp/lumen-20')
const L = require('../src/main.js'); const wait = ms => new Promise(r => setTimeout(r, ms))
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++ }
app.whenReady().then(async () => {
  await wait(4000); const w = L.windows[0], ex = s => w.ui.webContents.executeJavaScript(s)
  const errors = []; w.ui.webContents.on('console-message', e => { if (e.level === 'error' || e.level === 3) errors.push(e.message) })
  await ex(`document.querySelector('#intro .skip') && document.querySelector('#intro .skip').click()`); await wait(2500)
  await ex(`document.querySelector('#intro .go') && document.querySelector('#intro .go').click()`); await wait(1000)
  ok(!(await ex(`document.getElementById('bmbar').classList.contains('show')`)), 'no bar without bookmarks')
  const h0 = await ex(`document.getElementById('sidebar').offsetHeight`)
  for (let i = 0; i < 30; i++) L.D.addBookmark('https://site' + i + '.example/', 'Bookmark number ' + i)
  w.pushState(); await wait(1200)
  ok(await ex(`document.getElementById('bmbar').classList.contains('show')`), 'bar shows with bookmarks')
  const h1 = await ex(`document.getElementById('sidebar').offsetHeight`); ok(h1 > h0 + 20, 'toolbar grew for the bar ' + h0 + ' -> ' + h1)
  const vis = await ex(`[...document.querySelectorAll('.bm[data-i]')].filter(e => e.style.display !== 'none').length`)
  ok(vis > 3 && vis < 30 && await ex(`document.getElementById('bm-more').style.display !== 'none'`), 'overflow goes to the more menu (' + vis + ' visible)')
  ok(await ex(`(() => { const r = document.getElementById('bmbar').getBoundingClientRect(), u = document.getElementById('urlbar').getBoundingClientRect(); return r.top >= u.bottom })()`), 'bar sits under the address bar')
  await wait(600)
  const pageTop = w.active().view.getBounds().y; ok(pageTop >= h1 - 2, 'page moved down below the bar (' + pageTop + ')')
  fs.writeFileSync('/tmp/lumen-shots/v20-bm.png', (await w.ui.webContents.capturePage({ x: 0, y: 0, width: 1280, height: 130 })).toPNG())
  await ex(`document.querySelector('.bm[data-i="1"]').click()`); await wait(600)
  ok(/site1\.example/.test(w.active().url), 'click opens bookmark: ' + w.active().url)
  await ex(`api.do('setSetting','bookmarksBar',false)`); await wait(500)
  ok(!(await ex(`document.getElementById('bmbar').classList.contains('show')`)), 'setting hides the bar')
  await ex(`api.do('setSetting','bookmarksBar',true)`)
  L.D.settings.set({ blockedTotal: 12840 })
  const menu = Menu.getApplicationMenu(); let found = false; const walk = m => m.items.forEach(i => { if (i.label === 'Bookmarks Bar') found = true; if (i.submenu) walk(i.submenu) }); walk(menu); ok(found, 'menu item')
  const t = w.createTab('lumen://newtab', { active: true }); await wait(1800)
  const st = await t.view.webContents.executeJavaScript(`lumen.invoke('stats')`); ok(typeof st.blocked === 'number', 'stats available ' + JSON.stringify(st))
  ok(!errors.length, 'no UI errors ' + errors.join('|'))
  console.log(fails ? 'FAILED' : 'ALL PASS'); app.exit(fails ? 1 : 0)
})
