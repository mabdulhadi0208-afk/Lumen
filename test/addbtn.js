const fs = require('fs'); const { app } = require('electron')
fs.rmSync('/tmp/lumen-add', { recursive: true, force: true }); app.setPath('userData', '/tmp/lumen-add')
const L = require('../src/main.js'); const wait = ms => new Promise(r => setTimeout(r, ms))
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++ }
app.whenReady().then(async () => {
  await wait(4000); const w = L.windows[0], ex = s => w.ui.webContents.executeJavaScript(s)
  await ex(`document.querySelector('#intro .skip') && document.querySelector('#intro .skip').click()`); await wait(2500)
  await ex(`document.querySelector('#intro .go') && document.querySelector('#intro .go').click()`); await wait(1000)
  const a = w.createTab('lumen://newtab', { active: true }), b = w.createTab('lumen://newtab', { active: true }); await wait(800)
  const g = w.newGroup([a.id]); await wait(500)
  ok(await ex(`document.querySelectorAll('.tab .add').length >= 3`), 'every tab has a + button')
  await ex(`document.querySelector('.tab[data-id="${a.id}"] .add').click()`); await wait(800)
  const i = w.order.indexOf(a.id), n = w.tabs.get(w.order[i + 1])
  ok(n && n.id === w.activeId && n.id !== b.id, 'new tab opened right after it')
  ok(n && n.group === g, 'new tab joins the same group')
  await ex(`document.querySelector('.tab[data-id="${b.id}"]').dispatchEvent(new PointerEvent('pointerenter'))`)
  await ex(`document.querySelectorAll('.tab .add').forEach(e => e.style.opacity = 1)`); await wait(300)
  fs.writeFileSync('/tmp/lumen-shots/addbtn.png', (await w.ui.webContents.capturePage()).toPNG())
  L.D.settings.set({ tabLayout: 'side' }); await ex(`api.do('setSetting','tabLayout','side')`); await wait(1000)
  await ex(`document.querySelectorAll('.tab .add').forEach(e => e.style.opacity = 1)`); await wait(300)
  fs.writeFileSync('/tmp/lumen-shots/addbtn-side.png', (await w.ui.webContents.capturePage()).toPNG())
  console.log(fails ? 'FAILED' : 'ALL PASS'); app.exit(fails ? 1 : 0)
})
