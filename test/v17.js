const http = require('http'), fs = require('fs'); const { app } = require('electron')
http.createServer((q, r) => { r.setHeader('content-type', 'text/html'); r.end(`<title>Page ${q.url.slice(1)}</title><body style="margin:0;height:100vh;background:hsl(${q.url.length * 67 % 360} 70% 80%);font:60px sans-serif;display:grid;place-items:center">${q.url}</body>`) }).listen(48190)
fs.rmSync('/tmp/lumen-17', { recursive: true, force: true }); app.setPath('userData', '/tmp/lumen-17')
const L = require('../src/main.js'); const wait = ms => new Promise(r => setTimeout(r, ms))
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++ }
app.whenReady().then(async () => {
  await wait(4000); const w = L.windows[0], ex = s => w.ui.webContents.executeJavaScript(s)
  const errors = []; w.ui.webContents.on('console-message', e => { if (e.level === 'error' || e.level === 3) errors.push(e.message) })
  await ex(`document.querySelector('#intro .skip') && document.querySelector('#intro .skip').click()`); await wait(2500)
  await ex(`document.querySelector('#intro .go') && document.querySelector('#intro .go').click()`); await wait(1000)
  const ids = []; for (const p of ['a', 'bb', 'ccc', 'dddd']) { ids.push(w.createTab('http://127.0.0.1:48190/' + p, { active: true }).id); await wait(1700) }
  // layout: pretend mac full screen (no window buttons)
  await ex(`document.body.classList.remove('nonmac'); document.getElementById('wincontrols').style.display = 'none'`)
  const normal = await ex(`document.querySelector('.tab').getBoundingClientRect().left`)
  w.win.isFullScreen = () => true; w.pushState(); await wait(500)
  const fsLeft = await ex(`document.querySelector('.tab').getBoundingClientRect().left`)
  ok(normal > 70 && normal < 100, 'windowed: tabs start right after the window buttons (' + normal + ')')
  ok(fsLeft < 20, 'full screen: tabs start at the left edge (' + fsLeft + ')')
  const u = await ex(`JSON.stringify([document.querySelector('.navbtns').getBoundingClientRect().right, document.getElementById('urlbar').getBoundingClientRect().left])`)
  const [nr, ul] = JSON.parse(u); ok(ul >= nr && ul - nr < 20, 'address bar sits beside nav buttons ' + u)
  fs.writeFileSync('/tmp/lumen-shots/v17-top.png', (await w.ui.webContents.capturePage({ x: 0, y: 0, width: 1280, height: 100 })).toPNG())
  console.log('THUMBS', [...w.tabs.values()].map(t => t.url.slice(-5) + ':' + (t.thumb ? t.thumb.length : 0)).join(' ')); w.send('command', 'tabgrid'); await wait(1500)
  ok(await ex(`document.querySelectorAll('.tg-card').length`) === 5, 'overview shows all tabs')
  ok(await ex(`document.querySelectorAll('.tg-thumb > img').length`) >= 4, 'thumbnails: ' + await ex(`document.querySelectorAll('.tg-thumb > img').length`))
  fs.writeFileSync('/tmp/lumen-shots/v17-grid.png', (await w.ui.webContents.capturePage()).toPNG())
  await ex(`(() => { const i = document.getElementById('tg-q'); i.value = 'ccc'; i.dispatchEvent(new Event('input')) })()`); await wait(200)
  ok(await ex(`document.querySelectorAll('.tg-card').length`) === 1, 'search filters')
  await ex(`document.querySelector('.tg-card').click()`); await wait(700)
  ok(w.activeId === ids[2] && w.overlay === false, 'click switches tab and closes')
  w.send('command', 'tabgrid'); await wait(600)
  await ex(`document.querySelector('.tg-card[data-id="${ids[0]}"] .tg-x').click()`); await wait(600)
  ok(!w.tabs.has(ids[0]) && await ex(`document.querySelectorAll('.tg-card').length`) === 4, 'close from overview')
  await ex(`closeTabGrid()`); await wait(400)
  ok(!errors.length, 'no UI errors ' + errors.join('|'))
  console.log(fails ? 'FAILED' : 'ALL PASS'); app.exit(fails ? 1 : 0)
})
